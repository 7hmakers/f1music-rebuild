    /**
     * 合并默认值与文件内容，返回每个键对应的 Markdown 原文。
     */
    public static function all(): array
    {
        $content = self::defaults();
        foreach (self::keys() as $key) {
            $path = self::path($key);
            if (is_file($path)) {
                $value = @file_get_contents($path);
                if ($value !== false) {
                    $content[$key] = $value;
                }
            }
        }
        return $content;
    }

    /**
     * 返回每个键对应的已渲染 HTML。
     */
    public static function rendered(): array
    {
        $converter = self::converter();
        $rendered = [];
        foreach (self::all() as $key => $markdown) {
            $rendered[$key] = $converter->convert($markdown)->getContent();
        }
        return $rendered;
    }

    /**
     * 写入指定键的 Markdown（仅接受已知键）。
     */
    public static function put(array $values): void
    {
        $dir = self::dir();
        if (!is_dir($dir) && !@mkdir($dir, 0777, true) && !is_dir($dir)) {
            throw new RuntimeException('无法创建内容目录 config/content');
        }
        foreach ($values as $key => $markdown) {
            if (!array_key_exists($key, self::LABELS) || !is_string($markdown)) {
                continue;
            }
            $path = self::path($key);
            if (@file_put_contents($path, $markdown, LOCK_EX) === false) {
                throw new RuntimeException('无法写入内容文件 ' . $key . '.md');
            }
            @chmod($path, 0666);
        }
    }

    /**
     * 将默认值写入缺失的文件，返回实际创建的键。
     */
    public static function publish(): array
    {
        $dir = self::dir();
        if (!is_dir($dir)) {
            @mkdir($dir, 0777, true);
        }
        $defaults = self::defaults();
        $created = [];
        foreach (self::keys() as $key) {
            $path = self::path($key);
            if (!is_file($path)) {
                if (@file_put_contents($path, $defaults[$key], LOCK_EX) !== false) {
                    @chmod($path, 0666);
                    $created[] = $key;
                }
            }
        }
        return $created;
    }

    private static function converter(): CommonMarkConverter
    {
        return new CommonMarkConverter([
            'html_input' => 'strip',
            'allow_unsafe_links' => false,
            'max_nesting_level' => 20,
        ]);
    }
